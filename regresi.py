x2 = d[X2_VAR].to_numpy(float)
ones = np.ones_like(y)

# ---------------- MODEL 2D ----------------
res2d = {}
for xv, x in [(X1_VAR, x1), (X2_VAR, x2)]:
    r = ols(np.column_stack([ones, x]), y, ["Intersep", xv])
    res2d[xv] = r
    report(f"MODEL 2D: {Y_VAR} = b0 + b1*{xv}", r)

# ---------------- MODEL 3D ----------------
res3d = ols(np.column_stack([ones, x1, x2]), y, ["Intersep", X1_VAR, X2_VAR])
